// The text of src/generated/spec.ts, built from the copies in schemas/ and templates/register/.
// The engine never reads a file: it gets the schemas and the templates from this generated module.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export const VERSIONS = ['0.1', '0.2'];
export const TEMPLATES = ['register.md.tmpl', 'register.en.md.tmpl', 'register.fr.md.tmpl'];

/** @param {string} root the package root */
export function specModule(root) {
  const source = JSON.parse(readFileSync(join(root, 'schemas', 'SOURCE.json'), 'utf8'));
  const lines = [
    '// Generated by scripts/sync-spec.mjs from schemas/ and templates/register/. Do not edit.',
    '',
    `export const SPEC_SOURCE = ${JSON.stringify({ source: source.source, commit: source.commit, spec_versions: source.spec_versions })} as const;`,
    '',
    'export const SCHEMA_FILES: Readonly<Record<string, Readonly<Record<string, object>>>> = {',
  ];
  for (const version of VERSIONS) {
    lines.push(`  ${JSON.stringify(version)}: {`);
    const files = readdirSync(join(root, 'schemas', `v${version}`)).filter((f) => f.endsWith('.schema.json')).sort();
    for (const f of files) {
      const schema = JSON.parse(readFileSync(join(root, 'schemas', `v${version}`, f), 'utf8'));
      lines.push(`    ${JSON.stringify(f.replace(/\.schema\.json$/, ''))}: ${JSON.stringify(schema)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '', 'export const TEMPLATE_FILES: Readonly<Record<string, string>> = {');
  for (const t of TEMPLATES) lines.push(`  ${JSON.stringify(t)}: ${JSON.stringify(readFileSync(join(root, 'templates', 'register', t), 'utf8'))},`);
  lines.push('};', '');
  return lines.join('\n');
}
